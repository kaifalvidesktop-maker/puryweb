// PuryWeb — content/bridge.js (classic content script)
// Receives commands from the service worker; shows a light, readable toast inside a closed-off Shadow DOM.
(() => {
  if (window.__PW_BRIDGE__) return;
  window.__PW_BRIDGE__ = '0.1.0';

  const HOST_ID = 'puryweb-bridge-root';

  function getRoot() {
    let host = document.getElementById(HOST_ID);
    if (host) return host.shadowRoot;
    host = document.createElement('div');
    host.id = HOST_ID;
    host.style.cssText = 'all:initial;position:fixed;right:24px;bottom:24px;z-index:2147483647;';
    const root = host.attachShadow({ mode: 'open' });
    root.innerHTML = `
      <style>
        :host { all: initial; }
        .wrap { font-family: Inter, 'Noto Sans Bengali', system-ui, sans-serif; }
        .ring { padding: 2px; border-radius: 18px; background: linear-gradient(135deg, var(--from), var(--to));
                box-shadow: 0 12px 40px rgba(10,10,11,.18); animation: in .28s cubic-bezier(.2,.8,.2,1) both; }
        .card { display: flex; align-items: center; gap: 14px; background: #fff; color: #0A0A0B;
                border-radius: 16px; padding: 16px 20px; max-width: 360px; cursor: pointer; }
        .icon { width: 28px; height: 28px; flex: none; animation: spin .7s cubic-bezier(.4,0,.2,1) both; }
        .icon svg { display: block; }
        .msg { font-size: 18px; line-height: 1.5; font-weight: 500; }
        @keyframes spin { from { transform: rotate(0); } to { transform: rotate(180deg); } }
        @keyframes in { from { opacity: 0; transform: translateY(12px) scale(.98); } to { opacity: 1; transform: none; } }
        @media (prefers-reduced-motion: reduce) { .ring, .icon { animation: none; } }
      </style>
      <div class="wrap" id="slot"></div>`;
    document.documentElement.appendChild(host);
    return root;
  }

  let timer = 0;
  function toast({ message = '', iconSvg = '', theme = {}, duration = 3600 }) {
    const root = getRoot();
    const slot = root.getElementById('slot');
    const host = root.host;
    host.style.setProperty('--from', theme.from || '#FF6B35');
    host.style.setProperty('--to', theme.to || '#7C3AED');
    slot.textContent = '';
    const ring = document.createElement('div');
    ring.className = 'ring';
    const card = document.createElement('div');
    card.className = 'card';
    card.setAttribute('role', 'status');
    const icon = document.createElement('div');
    icon.className = 'icon';
    icon.innerHTML = iconSvg; // trusted: generated by the extension's own service worker
    const msg = document.createElement('div');
    msg.className = 'msg';
    msg.textContent = message;
    card.append(icon, msg);
    ring.appendChild(card);
    slot.appendChild(ring);
    const close = () => {
      clearTimeout(timer);
      host.remove();
    };
    card.addEventListener('click', close);
    clearTimeout(timer);
    timer = setTimeout(close, duration);
  }

  async function loadModule(path) {
    try {
      return await import(chrome.runtime.getURL(path));
    } catch (e) {
      return null;
    }
  }

  function pageInfo() {
    return {
      url: location.href,
      host: location.hostname.replace(/^www\./, ''),
      title: document.title,
      lang: document.documentElement.lang || '',
      forms: document.forms.length,
      inputs: document.querySelectorAll('input,select,textarea').length,
    };
  }

  async function openFeature(msg, featureKey, modulePath) {
    window.dispatchEvent(new CustomEvent('puryweb:' + msg.type.toLowerCase(), { detail: msg }));
    if (msg.features && msg.features[featureKey]) {
      const mod = await loadModule(modulePath);
      if (mod && typeof mod.open === 'function') {
        await mod.open(msg);
        return true;
      }
    }
    toast({ message: msg.message, iconSvg: msg.iconSvg, theme: msg.theme });
    return false;
  }

  chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
    if (sender.id !== chrome.runtime.id || !msg || typeof msg.type !== 'string') return false;
    switch (msg.type) {
      case 'PW_PING':
        sendResponse({ ok: true, version: window.__PW_BRIDGE__ });
        return false;
      case 'PW_PAGE_INFO':
        sendResponse({ ok: true, info: pageInfo() });
        return false;
      case 'PW_ANALYZE':
        loadModule('content/page-model.js').then((mod) => {
          if (!mod) return sendResponse({ ok: false, error: 'page-model unavailable' });
          try {
            const result = mod.analyze({ forceId: msg.forceId || null, maxChars: msg.maxChars || 24000 });
            sendResponse({ ok: true, summary: mod.summarize(result), ...(msg.full ? { ai: result.ai } : {}) });
          } catch (e) {
            sendResponse({ ok: false, error: String((e && e.message) || e) });
          }
        });
        return true;
      case 'PW_TOAST':
        toast(msg);
        sendResponse({ ok: true });
        return false;
      case 'PW_OPEN_INTENT':
        openFeature(msg, 'intentModal', 'content/intent-modal.js').then((shown) => sendResponse({ ok: true, shown }));
        return true;
      case 'PW_OPEN_PAYWALL':
        openFeature(msg, 'paywallModal', 'content/paywall.js').then((shown) => sendResponse({ ok: true, shown }));
        return true;
      default:
        return false;
    }
  });
})();
