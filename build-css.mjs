// Builds content/render-css.js (Tailwind utilities as a JS string, injected into the Shadow DOM).
// Usage: cd build && npm install && npm run css
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const tmp = path.join(here, '.out.css');
const bin = path.join(here, 'node_modules', '.bin', process.platform === 'win32' ? 'tailwindcss.cmd' : 'tailwindcss');

execFileSync(bin, ['-c', path.join(here, 'tailwind.config.js'), '-i', path.join(here, 'input.css'), '-o', tmp, '--minify'], { stdio: 'inherit', cwd: here });
const css = readFileSync(tmp, 'utf8');
rmSync(tmp);
const out = `// GENERATED by build/build-css.mjs — do not edit.\nexport const RENDER_CSS = ${JSON.stringify(css)};\n`;
writeFileSync(path.join(here, '..', 'content', 'render-css.js'), out);
console.log(`render-css.js written (${(css.length / 1024).toFixed(1)} KB)`);
